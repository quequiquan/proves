// La frase d'avui: la mateixa tot el dia, i una de diferent cada dia de l'any
function pindolaDelDia(d = new Date()) {
  const dia = Math.floor((Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) - Date.UTC(d.getFullYear(), 0, 1)) / 86400000);
  return PINDOLES[(dia + (d.getFullYear() % 7) * 53) % PINDOLES.length];
}
